/**
 * The font test page (design-language §14): every bundled weight with default, tabular and
 * slashed-zero figures and the numeric class, for a visual check in each webview.
 */
export function renderFontTest(): string {
  const sections = FONT_FACES.flatMap((face) => [
    `    <section aria-labelledby="${face.file}">`,
    `      <h2 id="${face.file}">${escapeHtml(face.family)} ${String(face.weight)}</h2>`,
    "      <table>",
    ...TEST_ROWS.map(
      ([label, variant, sample]) =>
        `        <tr><th scope="row">${escapeHtml(label)}</th><td style="font-family: '${face.family}'; font-weight: ${String(face.weight)}; font-variant-numeric: ${variant}" data-face="${face.file}" data-variant="${variant}">${sample}</td></tr>`,
    ),
    "      </table>",
    "    </section>",
  ]);
  const lines = [
    "<!doctype html>",
    // REUSE-IgnoreStart
    "<!-- SPDX-FileCopyrightText: 2026 SONARITHM contributors -->",
    "<!-- SPDX-License-Identifier: MIT OR Apache-2.0 -->",
    // REUSE-IgnoreEnd
    "<!-- Generated by `pnpm -C packages/ui tokens` from packages/ui/tokens/fonts.ts. Do not edit. -->",
    '<html lang="en">',
    "  <head>",
    '    <meta charset="utf-8">',
    "    <title>Font test: IBM Plex figures per weight</title>",
    '    <link rel="stylesheet" href="../src/generated/tokens.css">',
    '    <link rel="stylesheet" href="../src/generated/fonts.css">',
    "    <style>",
    "      body { background: var(--surface-0); color: var(--text-1); font-family: var(--font-sans); font-size: var(--type-13-size); line-height: var(--type-13-line); margin: var(--space-5); }",
    "      h1 { font-size: var(--type-18-size); line-height: var(--type-18-line); font-weight: var(--weight-semibold); }",
    "      h2 { font-size: var(--type-15-size); line-height: var(--type-15-line); font-weight: var(--weight-medium); margin-block: var(--space-5) var(--space-2); }",
    "      th { color: var(--text-2); font-weight: var(--weight-regular); text-align: start; padding-inline-end: var(--space-4); }",
    "      td { font-size: var(--type-18-size); }",
    "    </style>",
    "  </head>",
    "  <body>",
    "    <h1>IBM Plex figures per weight</h1>",
    "    <p>In each block the three numbers of the tabular rows must line up digit for digit, and the zero rows must show a slashed zero.</p>",
    ...sections,
    "  </body>",
    "</html>",
  ];
  return `${lines.join("\n")}\n`;
}
