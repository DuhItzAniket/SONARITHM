/** The global class readouts use for tabular, lining, slashed-zero figures (DL-X10). */
export const NUMERIC_CLASS = "snr-numeric";

/** Where `fonts.css` finds the font files, relative to `src/generated/`. */
const FONT_DIR = "../../fonts/";

function header(lines: readonly string[]): string[] {
  return [
    // The header of the generated file, not of this one.
    // REUSE-IgnoreStart
    "/* SPDX-FileCopyrightText: 2026 SONARITHM contributors */",
    "/* SPDX-License-Identifier: MIT OR Apache-2.0 */",
    // REUSE-IgnoreEnd
    "",
    "/*",
    ...lines.map((line) => ` * ${line}`),
    " */",
  ];
}

/** The @font-face rules and the numeric class. */
export function renderFontsCss(): string {
  const faces = FONT_FACES.flatMap((face) => [
    "",
    "@font-face {",
    `  font-family: "${face.family}";`,
    "  font-style: normal;",
    `  font-weight: ${String(face.weight)};`,
    "  font-display: swap;",
    `  src: url("${FONT_DIR}${face.file}") format("woff2");`,
    "}",
  ]);
  const lines = [
    ...header([
      "Generated by `pnpm -C packages/ui tokens` from packages/ui/tokens/fonts.ts. Do not edit.",
      "IBM Plex Sans and Mono from packages/ui/fonts: IBM's unmodified WOFF2 files under the",
      "SIL Open Font License 1.1 (packages/ui/fonts/LICENSE.txt). Only bundled files are",
      "loaded; nothing comes from the network or the system's font folders.",
    ]),
    ...faces,
    "",
    "/* Readouts: tabular, lining figures with a slashed zero (design-language §7.1, DL-X10). */",
    "@layer tokens.type {",
    `  .${NUMERIC_CLASS} {`,
    "    font-variant-numeric: var(--numeric);",
    "  }",
    "}",
  ];
  return `${lines.join("\n")}\n`;
}

/** The font notices for the app's licences view (12 §9): who, what, and the licence text. */
export function renderLicenses(licenseText: string): string {
  const families = Object.entries(FONT_SOURCES).map(([family, source]) => ({
    name: family,
    version: source.fontVersion,
    source: `npm ${source.package}@${source.version} (https://github.com/IBM/plex)`,
    license: "OFL-1.1",
    copyright: 'Copyright © 2017 IBM Corp. with Reserved Font Name "Plex"',
    modified: false,
    files: FONT_FACES.filter((face) => face.family === family).map(
      (face) => `packages/ui/fonts/${face.file}`,
    ),
  }));
  const record = {
    generatedBy: "pnpm -C packages/ui tokens (packages/ui/tokens/fonts.ts)",
    assets: families,
    // IBM's file has CRLF line endings; the notice text uses LF.
    licenseTexts: { "OFL-1.1": licenseText.replaceAll("\r\n", "\n") },
  };
  return `${JSON.stringify(record, null, 2)}\n`;
}

function escapeHtml(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

