//! The generated JSON Schema of the spec (04 §1). `cargo xtask codegen` writes it to
//! `schemas/sonarithm-spec-0.3.schema.json`, and CI fails when the committed file is stale.
//! The v0.1 schema stays committed beside it, unchanged, for editors of older files
//! (RFC-0004 §9).

use schemars::Schema;
use schemars::generate::SchemaSettings;
use schemars::transform::RecursiveTransform;
use serde_json::Value;

use crate::spec::Spec;

/// Where the schema is committed, relative to the workspace root.
pub const SCHEMA_PATH: &str = "schemas/sonarithm-spec-0.3.schema.json";

/// The JSON Schema (draft 2020-12) of [`Spec`], pretty-printed with a trailing newline.
#[must_use]
pub fn json_schema() -> String {
    // Optional keys are optional, not nullable: authors omit them rather than write null.
    let generator = SchemaSettings::draft2020_12()
        .with(|settings| {
            settings
                .transforms
                .push(Box::new(RecursiveTransform(not_nullable)));
        })
        .into_generator();
    let mut schema = generator.into_root_schema_for::<Spec>();
    schema.insert(
        "$comment".to_owned(),
        "Generated by `cargo xtask codegen` from the sonarithm-spec types; do not edit.".into(),
    );
    let mut text = serde_json::to_string_pretty(&schema).unwrap_or_default();
    text.push('\n');
    text
}

/// Turns `anyOf: [T, {"type": "null"}]` into `T` and drops `"null"` from type lists, which
/// schemars adds for every `Option`.
fn not_nullable(schema: &mut Schema) {
    let Some(object) = schema.as_object_mut() else {
        return;
    };
    if let Some(Value::Array(types)) = object.get_mut("type") {
        types.retain(|t| t != "null");
        if let [single] = types.as_slice() {
            let single = single.clone();
            object.insert("type".to_owned(), single);
        }
    }
    let null = serde_json::json!({ "type": "null" });
    let other = match object.get("anyOf") {
        Some(Value::Array(any)) if any.len() == 2 && any.contains(&null) => {
            any.iter().find(|branch| **branch != null).cloned()
        }
        _ => None,
    };
    if let Some(Value::Object(branch)) = other {
        object.remove("anyOf");
        for (key, value) in branch {
            object.entry(key).or_insert(value);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schema_names_the_top_level_keys_and_allows_only_x_extensions() {
        let schema: serde_json::Value = serde_json::from_str(&json_schema()).unwrap();
        assert_eq!(schema["title"], "SONARITHM spec");
        assert_eq!(schema["additionalProperties"], false);
        assert!(schema["patternProperties"]["^x-"].is_object());
        let required = schema["required"].as_array().unwrap();
        for key in ["specVersion", "data"] {
            assert!(required.iter().any(|k| k == key), "{key} is required");
        }
        // `tracks` or a `template` (v0.2).
        assert_eq!(
            schema["anyOf"],
            serde_json::json!([{ "required": ["tracks"] }, { "required": ["template"] }])
        );
    }

    #[test]
    fn optional_keys_are_not_nullable() {
        let schema = json_schema();
        // The one remaining null is `JsonValue::Null`, inside inline records.
        assert_eq!(schema.matches(r#""null""#).count(), 1);
        let value: Value = serde_json::from_str(&schema).unwrap();
        assert_eq!(value["properties"]["name"]["type"], "string");
        assert_eq!(value["properties"]["mode"]["$ref"], "#/$defs/Mode");
    }
}
