//! Provenance classes and confidence of data values (03 §4).
//!
//! Exact and estimated numbers must never become indistinguishable (P6, AGENTS.md rule 7):
//! every value carries a class and an optional confidence, and transforms propagate both.

use core::fmt;

use serde::{Deserialize, Serialize};

/// Where a value came from (03 §4, the `__snr_prov` column).
///
/// Variants are declared from strongest to weakest, so the derived [`Ord`] puts the weaker
/// class last and [`ProvenanceClass::weaker`] is a `max`. Non-estimates rank above
/// estimates, as rule 3 of 03 §4 requires. The relative order of the three estimate
/// classes is a convention (no study ranks them) to be revisited with PLOTSONA (C01).
#[derive(
    Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize,
)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum ProvenanceClass {
    /// Read directly from a data file. Absent provenance columns mean `exact` (03 §4 rule 1).
    #[default]
    Exact,
    /// Read from vector chart geometry (SVG, PDF vector, Office chart XML).
    Vector,
    /// Entered or corrected by a person.
    UserEdited,
    /// Computed by a transform from other values.
    Derived,
    /// Generated by SONARITHM (functions, stimulus generators).
    Synthetic,
    /// Estimated by classical computer vision from a raster image.
    CvEstimate,
    /// Estimated by a local machine-learning model.
    MlEstimate,
    /// Estimated by a cloud model (only with consent, ADR-0012).
    CloudEstimate,
}

impl ProvenanceClass {
    /// Whether the value is an estimate rather than a measurement, reading or edit.
    #[must_use]
    pub const fn is_estimate(self) -> bool {
        matches!(
            self,
            Self::CvEstimate | Self::MlEstimate | Self::CloudEstimate
        )
    }

    /// Whether descriptions may state the number plainly, without an estimate qualifier
    /// (03 §4 rule 3).
    #[must_use]
    pub const fn states_plainly(self) -> bool {
        matches!(self, Self::Exact | Self::Vector | Self::UserEdited)
    }

    /// The weaker of two classes, used when a value is computed from both (03 §4 rule 2).
    #[must_use]
    pub fn weaker(self, other: Self) -> Self {
        self.max(other)
    }
}

/// Confidence in a value, in [0, 1] (03 §4, the `__snr_conf` column).
#[derive(Clone, Copy, Debug, PartialEq, PartialOrd, Serialize, Deserialize)]
#[serde(try_from = "f32", into = "f32")]
pub struct Confidence(f32);

impl Confidence {
    /// Full confidence.
    pub const CERTAIN: Self = Self(1.0);

    /// A confidence, or `None` unless `value` is in [0, 1].
    #[must_use]
    pub fn new(value: f32) -> Option<Self> {
        (0.0..=1.0).contains(&value).then_some(Self(value))
    }

    /// The confidence as a number in [0, 1].
    #[must_use]
    pub const fn get(self) -> f32 {
        self.0
    }

    /// The lower of two confidences (03 §4 rule 2).
    #[must_use]
    pub fn min(self, other: Self) -> Self {
        if other.0 < self.0 { other } else { self }
    }
}

impl TryFrom<f32> for Confidence {
    type Error = ConfidenceOutOfRange;

    fn try_from(value: f32) -> Result<Self, Self::Error> {
        Self::new(value).ok_or(ConfidenceOutOfRange)
    }
}

impl From<Confidence> for f32 {
    fn from(confidence: Confidence) -> Self {
        confidence.0
    }
}

/// The error for a confidence outside [0, 1].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ConfidenceOutOfRange;

impl fmt::Display for ConfidenceOutOfRange {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("confidence must be a number from 0 to 1")
    }
}

impl std::error::Error for ConfidenceOutOfRange {}

/// The provenance of one value or of a derived set of values.
#[derive(Clone, Copy, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Provenance {
    /// The provenance class.
    pub class: ProvenanceClass,
    /// The confidence; `None` means not applicable, as for exact values (03 §4).
    pub confidence: Option<Confidence>,
}

impl Provenance {
    /// Exact data with no confidence attached.
    pub const EXACT: Self = Self {
        class: ProvenanceClass::Exact,
        confidence: None,
    };

    /// The provenance of a value computed from `self` and `other`: the weaker class and the
    /// lower confidence (03 §4 rule 2). A missing confidence counts as certain.
    #[must_use]
    pub fn combine(self, other: Self) -> Self {
        let confidence = match (self.confidence, other.confidence) {
            (Some(a), Some(b)) => Some(a.min(b)),
            (a, b) => a.or(b),
        };
        Self {
            class: self.class.weaker(other.class),
            confidence,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_exact_vector_and_user_edited_values_are_stated_plainly() {
        use ProvenanceClass::*;
        let plain: Vec<_> = [
            Exact,
            Vector,
            UserEdited,
            Derived,
            Synthetic,
            CvEstimate,
            MlEstimate,
            CloudEstimate,
        ]
        .into_iter()
        .filter(|class| class.states_plainly())
        .collect();
        assert_eq!(plain, [Exact, Vector, UserEdited]);
        assert!(CvEstimate.is_estimate() && !Derived.is_estimate());
    }

    #[test]
    fn combining_takes_the_weaker_class_and_the_lower_confidence() {
        let estimate = Provenance {
            class: ProvenanceClass::MlEstimate,
            confidence: Confidence::new(0.7),
        };
        let edited = Provenance {
            class: ProvenanceClass::UserEdited,
            confidence: Confidence::new(0.9),
        };
        let combined = edited.combine(estimate);
        assert_eq!(combined.class, ProvenanceClass::MlEstimate);
        assert_eq!(combined.confidence, Confidence::new(0.7));
        assert_eq!(
            Provenance::EXACT.combine(Provenance::EXACT),
            Provenance::EXACT
        );
        assert_eq!(Provenance::EXACT.combine(estimate), estimate);
    }

    #[test]
    fn confidence_is_limited_to_the_unit_interval() {
        assert_eq!(Confidence::new(1.5), None);
        assert_eq!(Confidence::new(f32::NAN), None);
        assert!(serde_json::from_str::<Confidence>("-0.1").is_err());
        assert_eq!(
            serde_json::to_string(&ProvenanceClass::CvEstimate).unwrap(),
            r#""cv_estimate""#
        );
    }
}
