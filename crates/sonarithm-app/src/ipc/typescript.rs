/// A binary view encoded by Rust with its expected contents, so the TypeScript reader is
/// tested against the real encoder.
#[must_use]
pub fn fixtures() -> String {
    use super::binary::{Values, sample};
    let view = sample();
    let bytes = view.encode().unwrap_or_default();
    let mut out = String::from(
        "// SPDX-FileCopyrightText: 2026 SONARITHM contributors\n\
         // SPDX-License-Identifier: MIT OR Apache-2.0\n\
         \n\
         // Generated by `cargo xtask codegen` from crates/sonarithm-app/src/ipc/binary.rs.\n\
         // Do not edit.\n\
         \n",
    );
    let _ = write!(
        out,
        "/** `binary::sample()` as encoded by Rust, in base64. */\n\
         export const SAMPLE_VIEW_BASE64 =\n  \"{}\";\n\n\
         /** What the sample holds; 64-bit integers as decimal strings. */\n\
         export const SAMPLE_VIEW = {{\n  kind: {},\n  generation: {},\n  rows: {},\n  columns: [\n",
        base64(&bytes),
        view.kind as u16,
        view.generation,
        view.rows,
    );
    for column in &view.columns {
        let (data_type, values) = match &column.values {
            Values::F64(v) => (1, join(v.iter().map(|x| format!("{x:?}")))),
            Values::I64(v) => (2, join(v.iter().map(|x| format!("\"{x}\"")))),
            Values::Utf8(v) => (3, join(v.iter().map(|x| format!("{x:?}")))),
            Values::Bool(v) => (4, join(v.iter().map(ToString::to_string))),
            Values::Provenance(v) => (5, join(v.iter().map(ToString::to_string))),
            Values::Confidence(v) => (6, join(v.iter().map(|x| format!("{x:?}")))),
        };
        let validity = column.validity.as_ref().map_or_else(
            || "null".to_owned(),
            |v| format!("[{}]", join(v.iter().map(ToString::to_string))),
        );
        let _ = writeln!(
            out,
            "    {{ name: {:?}, dataType: {data_type}, values: [{values}], validity: {validity} }},",
            column.name
        );
    }
    out.push_str("  ],\n} as const;\n");
    out
}

fn join(items: impl Iterator<Item = String>) -> String {
    items.collect::<Vec<_>>().join(", ")
}

/// Standard base64 with padding (RFC 4648 §4).
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        for i in 0..4 {
            if i <= chunk.len() {
                out.push(char::from(ALPHABET[((n >> (18 - 6 * i)) & 63) as usize]));
            } else {
                out.push('=');
            }
        }
    }
    out
}

/// The binary view header (ADR-0017 §6) as TypeScript constants.
fn binary_constants(out: &mut String) {
    let magic = String::from_utf8_lossy(&binary::MAGIC);
    let _ = write!(
        out,
        "/** The binary view layout (ADR-0017 §6); see crates/sonarithm-app/src/ipc/binary.rs. */\n\
         export const BINARY = {{\n  \
           magic: \"{magic}\",\n  \
           headerVersion: {},\n  \
           headerBytes: {},\n  \
           columnEntryBytes: {},\n  \
           align: {},\n  \
           flagValidity: {},\n  \
           offset: {{\n    \
             magic: {},\n    \
             version: {},\n    \
             kind: {},\n    \
             columns: {},\n    \
             reserved: {},\n    \
             rows: {},\n    \
             generation: {},\n    \
             columnType: {},\n    \
             columnFlags: {},\n    \
             columnNameLen: {},\n    \
             columnData: {},\n  \
           }},\n  \
           kind: {{\n",
        binary::HEADER_VERSION,
        binary::HEADER_BYTES,
        binary::COLUMN_ENTRY_BYTES,
        binary::ALIGN,
        binary::FLAG_VALIDITY,
        binary::offset::MAGIC,
        binary::offset::VERSION,
        binary::offset::KIND,
        binary::offset::COLUMNS,
        binary::offset::RESERVED,
        binary::offset::ROWS,
        binary::offset::GENERATION,
        binary::offset::COLUMN_TYPE,
        binary::offset::COLUMN_FLAGS,
        binary::offset::COLUMN_NAME_LEN,
        binary::offset::COLUMN_DATA,
    );
    for kind in ViewKind::ALL {
        let _ = writeln!(out, "    {}: {},", kind.name(), kind as u16);
    }
    out.push_str("  },\n  dataType: {\n");
    for data_type in DataType::ALL {
        let _ = writeln!(out, "    {}: {},", data_type.name(), data_type as u16);
    }
    out.push_str("  },\n} as const;\n\n");
    out.push_str(
        "/** Provenance class names by code (03 §4), for `provenance` columns. */\n\
         export const PROVENANCE_CLASSES = [",
    );
    let names: Vec<String> = sonarithm_data::provenance::CLASS_CODES
        .iter()
        .map(|class| format!("\"{}\"", sonarithm_data::provenance::class_name(*class)))
        .collect();
    out.push_str(&names.join(", "));
    out.push_str("] as const;\n\n");
    let _ = write!(
        out,
        "/** The code a strict reader reports for a buffer it cannot read (ADR-0017 §6). */
         export const BINARY_VIEW_ERROR = \"{}\";

",
        crate::codes::BINARY_VIEW.code
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_file_declares_every_type_once() {
        let file = typescript();
        for name in [
            "Request",
            "Reply",
            "IpcError",
            "Event",
            "Settings",
            "TransportState",
            "JobInfo",
        ] {
            let declaration = format!("export type {name} =");
            assert_eq!(file.matches(&declaration).count(), 1, "{name}");
        }
        assert!(file.contains("export const PROTOCOL_VERSION = 1;"));
        assert!(file.contains("magic: \"SNRV\""));
        // u64 values are numbers, not bigints.
        assert!(!file.contains("bigint"));
    }

    #[test]
    fn base64_matches_rfc_4648_vectors() {
        for (input, output) in [
            ("", ""),
            ("f", "Zg=="),
            ("fo", "Zm8="),
            ("foo", "Zm9v"),
            ("foob", "Zm9vYg=="),
            ("fooba", "Zm9vYmE="),
            ("foobar", "Zm9vYmFy"),
        ] {
            assert_eq!(base64(input.as_bytes()), output);
        }
    }

    #[test]
    fn requests_are_tagged_by_command_with_camel_case_args() {
        let file = typescript();
        assert!(file.contains("\"command\": \"transport_seek\""), "{file}");
        assert!(file.contains("startS: number"), "{file}");
    }
}
