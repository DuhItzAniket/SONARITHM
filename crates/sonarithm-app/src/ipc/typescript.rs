//! The TypeScript side of the protocol, generated from the Rust types with ts-rs (ADR-0011)
//! by `cargo xtask codegen` into `packages/ipc/src/generated/protocol.ts`. The UI uses only
//! these types; CI regenerates them and fails on a diff.

use std::fmt::Write as _;

