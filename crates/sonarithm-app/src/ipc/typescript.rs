/// Where the file goes, relative to the workspace root.
pub const PATH: &str = "packages/ipc/src/generated/protocol.ts";

fn declare<T: TS>(out: &mut String, cfg: &Config) {
    if let Some(docs) = T::docs() {
        out.push_str(&docs);
    }
    out.push_str("export ");
    out.push_str(&T::decl(cfg));
    out.push_str("\n\n");
}

/// The whole generated file.
#[must_use]
pub fn typescript() -> String {
    // u64 values (IDs, counts, generations) stay below 2^53, so they are plain numbers.
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(
        "// SPDX-FileCopyrightText: 2026 SONARITHM contributors\n\
         // SPDX-License-Identifier: MIT OR Apache-2.0\n\
         \n\
         // Generated by `cargo xtask codegen` from crates/sonarithm-app/src/ipc.rs (ADR-0011,\n\
         // ADR-0017). Do not edit: change the Rust types and run the codegen again.\n\
         \n",
    );
    let _ = writeln!(
        out,
        "/** The IPC protocol version host and UI must share (ADR-0017 §5). */\n\
         export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"
    );
    out.push_str("/** The reply each command gives. */\nexport const REPLY_KINDS = {\n");
    for (command, reply) in COMMANDS {
        let _ = writeln!(out, "  {command}: \"{reply}\",");
    }
    out.push_str(
        "} as const;\n\n/** The channel that carries each event. */\nexport const EVENT_CHANNELS = {\n",
    );
    for (event, channel) in EVENTS {
        let _ = writeln!(out, "  {event}: \"{channel}\",");
    }
    out.push_str(
        "} as const;\n\n\
         /** The reply each command gives, as a type. */\n\
         export type ReplyKinds = typeof REPLY_KINDS;\n\n\
         /** A command name, such as `transport_seek`. */\n\
         export type Command = Request[\"command\"];\n\n\
         /** The request type of one command. */\n\
         export type RequestFor<C extends Command> = Extract<Request, { command: C }>;\n\n\
         /** The reply type of one command. */\n\
         export type ReplyFor<C extends Command> = Extract<Reply, { reply: ReplyKinds[C] }>;\n\n",
    );
    binary_constants(&mut out);
    declare::<Request>(&mut out, &cfg);
    declare::<Reply>(&mut out, &cfg);
    declare::<IpcError>(&mut out, &cfg);
    declare::<Event>(&mut out, &cfg);
    declare::<Channel>(&mut out, &cfg);
    declare::<DatasetSummary>(&mut out, &cfg);
    declare::<FieldSummary>(&mut out, &cfg);
    declare::<DiagnosticInfo>(&mut out, &cfg);
    declare::<SpecState>(&mut out, &cfg);
    declare::<CompileReport>(&mut out, &cfg);
    declare::<Counts>(&mut out, &cfg);
    declare::<ScoreInfo>(&mut out, &cfg);
    declare::<TrackInfo>(&mut out, &cfg);
    declare::<PlaybackStatus>(&mut out, &cfg);
    declare::<LoopSpan>(&mut out, &cfg);
    declare::<TransportState>(&mut out, &cfg);
    declare::<ClockAnchor>(&mut out, &cfg);
    declare::<ExportRequest>(&mut out, &cfg);
    declare::<ExportResult>(&mut out, &cfg);
    declare::<JobKind>(&mut out, &cfg);
    declare::<JobState>(&mut out, &cfg);
    declare::<JobInfo>(&mut out, &cfg);
    declare::<HistoryState>(&mut out, &cfg);
    declare::<DeviceSummary>(&mut out, &cfg);
    declare::<Settings>(&mut out, &cfg);
    declare::<AudioSettings>(&mut out, &cfg);
    declare::<Theme>(&mut out, &cfg);
    declare::<Verbosity>(&mut out, &cfg);
    declare::<Modalities>(&mut out, &cfg);
    declare::<Consent>(&mut out, &cfg);
    let trimmed = out.trim_end().len();
    out.truncate(trimmed);
    out.push('\n');
    out
}

